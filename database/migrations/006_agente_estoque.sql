CREATE TABLE recomendacao_estoque (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    item_id bigint NOT NULL,
    analisado_em timestamptz NOT NULL,
    inicio_janela timestamptz NOT NULL,
    saldo numeric(14,4) NOT NULL CHECK (saldo >= 0),
    limite_minimo numeric(14,4) NOT NULL CHECK (limite_minimo >= 0),
    dias_observados integer NOT NULL CHECK (dias_observados >= 0),
    dias_com_consumo integer NOT NULL CHECK (dias_com_consumo >= 0),
    consumo_total numeric(14,4) NOT NULL CHECK (consumo_total > 0),
    consumo_diario numeric NOT NULL CHECK (consumo_diario > 0),
    previsao_dias numeric(14,2) NOT NULL CHECK (previsao_dias >= 0),
    mae numeric CHECK (mae IS NULL OR mae >= 0),
    justificativa text NOT NULL CHECK (btrim(justificativa) <> ''),
    ultimo_movimento_id bigint NOT NULL REFERENCES movimentacao_estoque(id),
    situacao text NOT NULL DEFAULT 'PENDENTE'
        CHECK (situacao IN ('PENDENTE', 'ACEITA', 'DESCARTADA')),
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    atualizado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    decidido_por bigint,
    decidido_em timestamptz,
    FOREIGN KEY (item_id, laboratorio_id) REFERENCES item_estoque(id, laboratorio_id),
    FOREIGN KEY (decidido_por, laboratorio_id) REFERENCES usuario(id, laboratorio_id),
    CHECK ((situacao = 'PENDENTE' AND decidido_por IS NULL AND decidido_em IS NULL)
        OR (situacao <> 'PENDENTE' AND decidido_por IS NOT NULL AND decidido_em IS NOT NULL)),
    UNIQUE (laboratorio_id, item_id, ultimo_movimento_id)
);

-- Uma única recomendação pendente por lote, inclusive sob chamadas concorrentes.
CREATE UNIQUE INDEX recomendacao_pendente_por_lote_idx
    ON recomendacao_estoque(laboratorio_id, item_id) WHERE situacao = 'PENDENTE';
CREATE INDEX recomendacao_por_laboratorio_idx
    ON recomendacao_estoque(laboratorio_id, analisado_em DESC);

CREATE FUNCTION tg_proteger_decisao_recomendacao() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Recomendações e decisões não podem ser apagadas.' USING ERRCODE = '23514';
    END IF;
    IF OLD.situacao <> 'PENDENTE' THEN
        RAISE EXCEPTION 'Decisão final de recomendação é imutável.' USING ERRCODE = '23514';
    END IF;
    IF NEW.laboratorio_id <> OLD.laboratorio_id OR NEW.item_id <> OLD.item_id
       OR NEW.criado_em <> OLD.criado_em THEN
        RAISE EXCEPTION 'Identidade e data de criação são imutáveis.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER recomendacao_proteger_decisao
    BEFORE UPDATE OR DELETE ON recomendacao_estoque
    FOR EACH ROW EXECUTE FUNCTION tg_proteger_decisao_recomendacao();
CREATE TRIGGER recomendacao_sem_truncate
    BEFORE TRUNCATE ON recomendacao_estoque
    FOR EACH STATEMENT EXECUTE FUNCTION tg_historico_imutavel();

